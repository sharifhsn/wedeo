#!/usr/bin/env python3
"""Extract constant C tables from the pinned FFmpeg n9.1 submodule into verified Rust modules.

Usage:
    python3 tools/extract_tables.py \\
        --source FFmpeg/libavcodec/h264_cabac.c \\
        --symbol cabac_context_init_I:i8 \\
        --out codecs/wedeo-codec-h264/src/tables_gen.rs
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import re
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent


def ffmpeg_commit() -> str:
    ff = REPO_ROOT / "FFmpeg"
    try:
        sha = subprocess.check_output(
            ["git", "-C", str(ff), "rev-parse", "HEAD"], text=True
        ).strip()
        tag = subprocess.check_output(
            ["git", "-C", str(ff), "describe", "--tags", "--always"], text=True
        ).strip()
        return f"{tag} ({sha})"
    except Exception:
        return "unknown"


def strip_c_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def extract_c_array(text: str, name: str) -> tuple[list[int], str]:
    """Extract dimensions and initializer body of a static/const C array."""
    pattern = re.compile(
        rf"\b{re.escape(name)}\s*((?:\[\s*[^]]*\s*\])+)\s*=\s*\{{",
        re.M,
    )
    m = pattern.search(text)
    if not m:
        raise ValueError(f"C array symbol '{name}' not found")
    dims_raw = re.findall(r"\[\s*([^]]*)\s*\]", m.group(1))
    # Balance braces from the opening '{'
    start = m.end() - 1
    depth = 0
    end = start
    for i in range(start, len(text)):
        ch = text[i]
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                end = i + 1
                break
    if depth != 0:
        raise ValueError(f"Unbalanced braces while parsing '{name}'")
    body = text[start:end]
    # Infer numeric dimensions where explicit
    dims: list[int] = []
    for d in dims_raw:
        d = d.strip()
        dims.append(int(d, 0) if d.isdigit() else 0)
    return dims, body


def c_init_to_rust(body: str) -> str:
    body = body.replace("{", "[").replace("}", "]")
    body = re.sub(r"\s+", " ", body).strip()
    return body


def count_nested_dims(rust_body: str) -> list[int]:
    """Compute exact rectangular dimensions of a Rust nested array literal."""
    import ast

    parsed = ast.literal_eval(rust_body)
    dims: list[int] = []
    cur = parsed
    while isinstance(cur, list):
        dims.append(len(cur))
        cur = cur[0] if cur else None
    return dims


def rust_array_type(elem_ty: str, dims: list[int]) -> str:
    ty = elem_ty
    for d in reversed(dims):
        ty = f"[{ty}; {d}]"
    return ty


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", required=True, help="Path to C file inside FFmpeg/")
    ap.add_argument(
        "--symbol",
        action="append",
        required=True,
        help="Symbol spec in the form c_name:rust_type (e.g. my_tab:u8)",
    )
    ap.add_argument("--out", required=True, help="Output Rust file path")
    args = ap.parse_args()

    src_path = (REPO_ROOT / args.source).resolve()
    raw = src_path.read_text(encoding="utf-8")
    sha256 = hashlib.sha256(raw.encode("utf-8")).hexdigest()
    clean = strip_c_comments(raw)

    lines = [
        "// AUTO-GENERATED by tools/extract_tables.py — DO NOT EDIT BY HAND.",
        f"// Source: {args.source} @ FFmpeg {ffmpeg_commit()}",
        f"// Source SHA-256: {sha256}",
        "",
    ]

    for spec in args.symbol:
        if ":" not in spec:
            raise ValueError(f"Expected name:rust_type, got '{spec}'")
        name, elem_ty = spec.split(":", 1)
        _, body = extract_c_array(clean, name)
        rust_body = c_init_to_rust(body)
        dims = count_nested_dims(rust_body)
        arr_ty = rust_array_type(elem_ty, dims)
        const_name = name.upper()
        lines.append(f"pub const {const_name}: {arr_ty} = {rust_body};")
        lines.append("")

    out_path = (REPO_ROOT / args.out).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({len(args.symbol)} symbol(s) from {args.source})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
